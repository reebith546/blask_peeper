from django.contrib.auth.models import User

# Название группы директора и разделов, которые директор может выдавать продавцам.
# Вынесено сюда одним местом — на эти строки ссылаются admin.py и management-команда
# setup_roles, чтобы не разъезжались при переименовании.
DIRECTOR_GROUP_NAME = 'Директор магазина'
SELLER_SECTION_GROUPS = {
    'catalog': 'Продавец: Каталог',
    'orders': 'Продавец: Заказы',
    'reviews': 'Продавец: Отзывы',
    'content': 'Продавец: Контент главной',
}


class SellerAccount(User):
    """Прокси-модель поверх User — отдельный раздел «Продавцы» в админке.

    Директор магазина управляет учётками только через этот раздел: видит
    только продавцов (не других директоров и не владельца), выбирает права
    только из заранее заданных групп по разделам — так исключена возможность
    случайно или намеренно выдать себе/продавцу более широкий доступ.
    """

    class Meta:
        proxy = True
        verbose_name = 'Продавец'
        verbose_name_plural = 'Продавцы'
