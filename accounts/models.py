from django.contrib.auth.models import User

# Название группы директора и разделов, которые директор может выдавать продавцам.
# Вынесено сюда одним местом — на эти строки ссылаются admin.py и management-команда
# setup_roles, чтобы не разъезжались при переименовании.
DIRECTOR_GROUP_NAME = 'Директор магазина'
SELLER_SECTION_GROUPS = {
    'catalog': 'Продавец: Каталог',
    'orders': 'Продавец: Заказы',
    'reviews': 'Продавец: Отзывы',
    'content': 'Продавец: Контент главной',
}

# Роли, которыми оперирует раздел «Сотрудники». Владельца (superuser) здесь нет —
# он управляется через штатный раздел «Пользователи» и в этот список не попадает.
ROLE_SELLER = 'seller'
ROLE_DIRECTOR = 'director'
ROLE_CHOICES = (
    (ROLE_SELLER, 'Продавец'),
    (ROLE_DIRECTOR, 'Директор магазина'),
)


class SellerAccount(User):
    """Прокси-модель поверх User — раздел «Сотрудники» в админке.

    Через этот раздел директор управляет всей командой: и продавцами, и другими
    директорами. Ключевые ограничения (см. accounts/admin.py):

    - в списке нет владельцев (superuser) — их заводит только сам владелец;
    - роль выбирается из фиксированного списка (Продавец / Директор), а права —
      из заранее заданных групп-разделов; произвольные Django-права и флаг
      суперпользователя через эту форму выдать нельзя;
    - нельзя деактивировать самого себя и последнего активного директора;
    - учётки не удаляются, только деактивируются.
    """

    class Meta:
        proxy = True
        verbose_name = 'Сотрудник'
        verbose_name_plural = 'Сотрудники'

    def is_director(self):
        return self.groups.filter(name=DIRECTOR_GROUP_NAME).exists()
